import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { extname, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const sourceRoot = join(root, 'src');
const phosphorRoot = join(root, 'node_modules', '@phosphor-icons', 'web', 'src');
const outputRoot = join(root, 'static', 'fonts');
const cssPath = join(sourceRoot, 'lib', 'styles', 'phosphor-subset.css');
const classPattern = /\bph-([a-z0-9-]+)\b/g;
const sourceExtensions = new Set(['.svelte', '.ts', '.css', '.html']);

function sourceFiles(directory) {
	const files = [];
	for (const entry of readdirSync(directory, { withFileTypes: true })) {
		const path = join(directory, entry.name);
		if (entry.isDirectory()) files.push(...sourceFiles(path));
		else if (sourceExtensions.has(extname(entry.name))) files.push(path);
	}
	return files;
}

const usedNames = new Set();
for (const file of sourceFiles(sourceRoot)) {
	for (const match of readFileSync(file, 'utf8').matchAll(classPattern)) {
		if (match[1] !== 'fill') usedNames.add(match[1]);
	}
}

// Fill glyphs are used by active navigation, status feedback and playback.
// Keeping this explicit prevents the filled font from carrying every regular
// icon merely because both weights share the same class names.
const usedFillNames = new Set([
	'bookmark-simple', 'books', 'broadcast', 'chart-line-up', 'check-circle',
	'compass', 'dots-three-circle', 'eye-slash', 'gear', 'gear-six', 'heart',
	'info', 'lightning', 'magnifying-glass', 'newspaper', 'pause', 'play',
	'shield-star', 'sparkle', 'squares-four', 'tray', 'user-circle',
	'warning-circle', 'waveform'
]);

function catalogue(style) {
	const selection = JSON.parse(readFileSync(join(phosphorRoot, style, 'selection.json'), 'utf8'));
	return new Map(
		selection.icons.map(({ properties }) => [
			style === 'fill' ? properties.name.replace(/-fill$/, '') : properties.name,
			properties.code
		])
	);
}

/**
 * HarfBuzz first, fontTools second.
 *
 * `hb-subset` is a system package, and on a machine without it this script used
 * to die with a bare ENOENT — which meant the icon set could not be regenerated
 * at all, so adding one icon quietly became a blocked task. `pyftsubset` ships
 * with fontTools, produces an equivalent subset for this input, and is far more
 * likely to already be present. Either tool is fine; having only one is not.
 */
function runSubsetter(input, unicodes, output) {
	const attempts = [
		{ file: 'hb-subset', args: [input, `--unicodes=${unicodes}`, `--output-file=${output}`] },
		{
			file: 'pyftsubset',
			args: [input, `--unicodes=${unicodes}`, `--output-file=${output}`, '--no-ignore-missing-unicodes']
		}
	];
	const failures = [];
	for (const { file, args } of attempts) {
		try {
			execFileSync(file, args, { stdio: 'pipe' });
			return file;
		} catch (error) {
			failures.push(`${file}: ${error.code ?? error.message}`);
		}
	}
	throw new Error(
		[
			'No font subsetter available.',
			'Install HarfBuzz (hb-subset) or fontTools (pip install fonttools).',
			...failures
		].join(' ')
	);
}

function subset(style, fontName, outputName) {
	const icons = catalogue(style);
	const selected = [...(style === 'fill' ? usedFillNames : usedNames)]
		.filter((name) => icons.has(name))
		.sort()
		.map((name) => ({ name, code: icons.get(name) }));
	const unicodes = selected.map(({ code }) => `U+${code.toString(16).toUpperCase()}`).join(',');
	const tool = runSubsetter(join(phosphorRoot, style, fontName), unicodes, join(outputRoot, outputName));
	console.log(`  ${outputName}: ${selected.length} glyphs via ${tool}`);
	return selected;
}

mkdirSync(outputRoot, { recursive: true });
const regular = subset('regular', 'Phosphor.ttf', 'phosphor-regular-subset.ttf');
const fill = subset('fill', 'Phosphor-Fill.ttf', 'phosphor-fill-subset.ttf');

const declarations = (icons, prefix) =>
	icons.map(({ name, code }) => `.${prefix}.ph-${name}::before{content:"\\${code.toString(16)}"}`).join('\n');

writeFileSync(
	cssPath,
	`/* Generated by scripts/generate-icon-subset.mjs. */
@font-face{font-family:"Phosphor Subset";src:url("/fonts/phosphor-regular-subset.ttf") format("truetype");font-display:swap}
@font-face{font-family:"Phosphor Fill Subset";src:url("/fonts/phosphor-fill-subset.ttf") format("truetype");font-display:swap}
.ph,.ph-fill{display:inline-block;font-style:normal;font-variant:normal;font-weight:normal;line-height:1;text-transform:none;speak:never;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}
.ph{font-family:"Phosphor Subset"!important}
.ph-fill{font-family:"Phosphor Fill Subset"!important}
${declarations(regular, 'ph')}
${declarations(fill, 'ph-fill')}
`
);

console.log(`Generated ${regular.length} regular and ${fill.length} fill glyphs.`);
